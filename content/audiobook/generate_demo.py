import asyncio
import os
import subprocess
import sys
import edge_tts

sys.stdout.reconfigure(encoding='utf-8')

VOICE = "ru-RU-DmitryNeural"
RATE = "-2%"

DEMO_TEXT = """Владимир Аньянов. Внутренний ток: Архитектура счастья. 
Инженерное руководство по электродинамике сознания.

Главная аксиома книги: «Счастье — это режим сверхпроводимости цепи».

Мы не создавали законы человеческой природы заново. Мы открыли строгую инженерную архитектуру счастья — перевели вековую интуицию и хаос человеческого опыта в прикладную, проверяемую и ремонтируемую систему. Душевный разлад — это не экзистенциальное проклятие, а омический перегрев или утечка на землю, поддающиеся точной локализации и отладке приборами ясного внимания.

Слово к русскому изданию.
Русский синтез: от омического ада к чертежу Циолковского.

«Внутренний ток» не мог родиться ни в одной другой точке земного шара.

Западная мысль, ослеплённая утилитаризмом и формулами, двести лет строила турбины, полупроводники и квантовые компьютеры, высокомерно оставив человеческую душу за скобками — как субъективный шум и область для священников. Восточная традиция веками хранила бесценную соматическую тишину Тандэна и состояние Мусин, но держала их запертыми на циновках монастырей, пряча простоту устройства человека за туманом коанов и парадоксов.

Россия исторически оказалась той единственной наковальней, где эти два полушария бытия сошлись в предельном, мучительном напряжении.

С одной стороны — беспощадная строгость русской академической школы. В 1842 году на Васильевском острове в Санкт-Петербурге академик Эмилий Христианович Ленц дал миру строгий математический расчёт тепловых потерь проводника — закон Джоуля — Ленца: количество тепла Ку равно произведению квадрата силы тока на сопротивление и время. 

Это та же самая культура мысли, которая подарила планете таблицу Менделеева, фундаментальную теоретическую физику и первый космический полёт. Русская инженерная традиция никогда не терпела приблизительности: закон сохранения энергии свят, расчёт должен сходиться до десятого знака.

С другой стороны — сокрушительная, обнажённая глубина русской духовной драмы. Ни в одной литературе мира вопрос о природе душевной боли не стоял так остро, как у нас. 

В своей «Исповеди» Лев Толстой описал предельный экзистенциальный тупик: имея всемирную славу, семью и богатство, он прятал верёвку, чтобы не повеситься в собственном кабинете, потому что искал оправдания каждого своего шага перед вымышленным внешним судьёй. 

А Фёдор Достоевский вскрыл механику подпольного человека — того самого внутреннего залома, когда гордыня и сопротивление реальности сжигают проводку нервной системы дотла.

Веками эти два полюса в России вели войну на уничтожение. Духовные искатели презирали «сухую физику», а учёные отмахивались от мук совести, оставляя человека на растерзание бесконечной вине и морализаторству.

«Внутренний ток» ликвидирует этот вековой раскол.

Мы взяли предельную честность русской классики к человеческому страданию и соединили её со строгим чертежом Циолковского. Человек — не испорченное грехом существо, обречённое на вечное покаяние, и не случайный набор психологических комплексов. Человек — это замкнутый электрический контур. Страдание и душевная гарь — это не проклятие, а буквальный омический перегрев проводки по закону Джоуля — Ленца при зажатом сопротивлении эго.

То, о чём Достоевский писал романы-катастрофы, а Толстой мучился в нравственных терзаниях, решается снятием залома со шланга внимания, сбросом сопротивления в ноль и прямым замыканием созидательного тока на реальность.

Этот синтез завершён. Наука и дух говорят на одном языке.
"""

CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(CURRENT_DIR, "..", ".."))
RAW_AUDIO = os.path.join(CURRENT_DIR, "raw_demo.mp3")
MASTER_MP3 = os.path.join(CURRENT_DIR, "00_Слово_к_русскому_изданию_Демо.mp3")
COVER_PATH = os.path.join(PROJECT_ROOT, "public", "assets", "book_cover.jpg")

async def synthesize():
    print(f"[1/3] Синтез голоса {VOICE} (скорость {RATE})...")
    comm = edge_tts.Communicate(DEMO_TEXT.strip(), VOICE, rate=RATE)
    await comm.save(RAW_AUDIO)
    print(f"      Сырой файл сгенерирован: {os.path.getsize(RAW_AUDIO):,} байт")

def master_audio():
    print("[2/3] Мастеринг FFmpeg (EBU R128 / ACX -16 LUFS) + обложка и теги...")
    cmd = [
        "ffmpeg", "-y",
        "-i", RAW_AUDIO,
    ]
    has_cover = os.path.exists(COVER_PATH)
    if has_cover:
        cmd.extend(["-i", COVER_PATH])

    # Loudnorm filter
    cmd.extend([
        "-filter_complex", "[0:a]loudnorm=I=-16:TP=-1.5:LRA=11[aout]"
    ])

    if has_cover:
        cmd.extend([
            "-map", "[aout]",
            "-map", "1:0",
            "-c:a", "libmp3lame",
            "-b:a", "192k",
            "-c:v", "copy",
            "-id3v2_version", "3",
            "-metadata:s:v", 'title="Cover"',
            "-metadata:s:v", 'comment="Cover (front)"'
        ])
    else:
        cmd.extend([
            "-map", "[aout]",
            "-c:a", "libmp3lame",
            "-b:a", "192k",
            "-id3v2_version", "3"
        ])

    cmd.extend([
        "-metadata", 'title=Слово к русскому изданию: Русский синтез',
        "-metadata", 'artist=Владимир Аньянов',
        "-metadata", 'album_artist=Владимир Аньянов',
        "-metadata", 'album=Внутренний ток: Архитектура счастья',
        "-metadata", 'composer=Владимир Аньянов',
        "-metadata", 'track=01/01',
        "-metadata", 'disc=1/1',
        "-metadata", 'genre=Audiobook',
        "-metadata", 'date=2026',
        "-metadata", 'comment=Официальная аудиокнига «Внутренний ток: Архитектура счастья»',
        MASTER_MP3
    ])

    res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    if res.returncode != 0:
        print("Ошибка FFmpeg:", res.stderr)
        sys.exit(1)

    print(f"[3/3] Готово! Итоговый мастер-трек: {MASTER_MP3}")
    print(f"      Размер: {os.path.getsize(MASTER_MP3):,} байт")
    if os.path.exists(RAW_AUDIO):
        os.remove(RAW_AUDIO)

if __name__ == "__main__":
    asyncio.run(synthesize())
    master_audio()
