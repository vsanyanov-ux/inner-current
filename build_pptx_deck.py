prs = Presentation()
# 16:9 widescreen layout
prs.slide_width = Inches(13.333333)
prs.slide_height = Inches(7.5)

blank_layout = prs.slide_layouts[6]

for i in range(1, 13):
    slide = prs.slides.add_slide(blank_layout)
    img_name = f"slide_{i:02d}.png"
    img_path = os.path.join(SLIDES_IMG_DIR, img_name)
    
    if os.path.exists(img_path):
        # Insert image full-bleed covering the entire slide
        slide.shapes.add_picture(img_path, Inches(0), Inches(0), width=prs.slide_width, height=prs.slide_height)
    else:
        print(f"Warning: Image {img_path} not found!")

    # Attach speaker notes for presenter view
    notes_slide = slide.notes_slide
    text_frame = notes_slide.notes_text_frame
    text_frame.text = SPEAKER_NOTES.get(i, "")

# Save to project and Obsidian Vault
prs.save(PPTX_PATH)
prs.save(PPTX_VAULT_PATH)

